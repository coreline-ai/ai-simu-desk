import {buildLivingOffice} from './build-living-office.mjs';
import {buildLivingPage} from './build-living-page.mjs';
import {buildEnsembleOffice} from './build-ensemble-office.mjs';
import{buildFinalOffice}from'./build-final-office.mjs';
import{assertMutableOutput}from'./build-output-guard.mjs';
import {buildActivities,buildTeamActivities} from './build-activities.mjs';
import {buildRoomQuality,buildRoomPage} from './build-room-quality.mjs';
import{buildOfficeV5}from'./build-office-v5.mjs';
import{buildOfficePage}from'./build-office-page.mjs';
import {build,transform} from 'esbuild';
import {buildSamplePage} from './build-sample-page.mjs';
import {buildLibrary} from './build-library.mjs';
import {mkdir,copyFile,readFile,writeFile,rm} from 'node:fs/promises';
export async function buildClient(remote=false) {await assertMutableOutput();
  await import('./build-team.mjs');
  await rm('product/dist',{recursive:true,force:true});await mkdir('product/dist/assets',{recursive:true});
  await build({entryPoints:['product/src/app.mjs'],outfile:'product/dist/assets/app.js',bundle:true,format:'esm',minify:true,target:['es2022'],legalComments:'linked'});
  const html=await readFile('product/index.html','utf8');
  await writeFile('product/dist/index.html',remote?html.replaceAll('LOCAL FAKE AI','FAKE AI').replaceAll('LOCAL EDITION','SHARED EDITION').replaceAll('이 기기의 서버','연결된 서버'):html);
  for(const [from,to] of [['product/assets/studio-team-v4.glb','studio-team-v4.glb'],['demo/assets/office-background-v1.png','office-background-v1.png']])await copyFile(from,`product/dist/assets/${to}`);
  const css=await transform(await readFile('product/styles.css','utf8'),{loader:'css',minify:true});
  if(css.warnings.length)throw new Error('Product stylesheet validation failed');
  await writeFile('product/dist/assets/styles.css',css.code);
  await buildOfficeV5();
  await buildOfficePage();
  await buildRoomQuality();
  await buildRoomPage();
  await buildFinalOffice();
  await copyFile('product/assets/studio-room-v7.glb','product/dist/assets/studio-room-v7.glb');
  await buildEnsembleOffice();
  await copyFile('product/assets/studio-room-v8.glb','product/dist/assets/studio-room-v8.glb');
  await buildLivingOffice();await copyFile('product/assets/studio-room-v9.glb','product/dist/assets/studio-room-v9.glb');await buildLivingPage();
  await buildActivities();
  await buildTeamActivities();
  await buildSamplePage();
  await buildLibrary(remote);
}
